import fs from 'node:fs'
import path from 'node:path'

const drizzleDir = path.resolve(process.cwd(), 'drizzle')
const outFile = path.resolve(
  process.cwd(),
  'src/server/db/d1-dev-migrations.generated.ts',
)

type JournalEntry = { tag: string }

const journalPath = path.join(drizzleDir, 'meta/_journal.json')

if (!fs.existsSync(journalPath)) {
  const emptyOutput = `// Auto-generated fallback when no migrations exist yet
export interface BundledMigration {
  tag: string
  sql: string
}

export const bundledMigrations: Array<BundledMigration> = []
`
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, emptyOutput)
  console.info('No migrations found yet. Generated empty bundledMigrations.')
  process.exit(0)
}

const journal = JSON.parse(fs.readFileSync(journalPath, 'utf8')) as {
  entries: Array<JournalEntry>
}

const escapeTemplate = (value: string) =>
  value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')

const lines = journal.entries.map((entry) => {
  const sqlPath = path.join(drizzleDir, `${entry.tag}.sql`)
  const sql = fs.existsSync(sqlPath) ? fs.readFileSync(sqlPath, 'utf8') : ''

  return `  {\n    tag: ${JSON.stringify(entry.tag)},\n    sql: \`${escapeTemplate(sql)}\`,\n  },`
})

const output = `// AUTO-GENERATED by scripts/bundle-d1-migrations.ts -- do not edit.
// Regenerated automatically as part of \`pnpm db:generate\`.

export interface BundledMigration {
  tag: string
  sql: string
}

export const bundledMigrations: Array<BundledMigration> = [
${lines.join('\n')}
]
`

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, output)
console.info(
  `Bundled ${journal.entries.length} migration(s) -> ${path.relative(process.cwd(), outFile)}`,
)
